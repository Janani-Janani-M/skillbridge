CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(256) NOT NULL,
 role VARCHAR(10) NOT NULL CHECK(role IN ('STUDENT','ADMIN')),
 department VARCHAR(100) NOT NULL DEFAULT '',
 cgpa DECIMAL(4,2) NOT NULL DEFAULT 0 CHECK(cgpa BETWEEN 0 AND 10),
 graduation_year INT NOT NULL DEFAULT 2027 CHECK(graduation_year BETWEEN 2000 AND 2100),
 bio VARCHAR(1500) NOT NULL DEFAULT '',
 portfolio VARCHAR(400) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS skills (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS student_skills (
 user_id BIGINT NOT NULL REFERENCES users(id),
 skill_id BIGINT NOT NULL REFERENCES skills(id),
 level INT NOT NULL CHECK(level BETWEEN 1 AND 3),
 PRIMARY KEY(user_id,skill_id)
);
CREATE TABLE IF NOT EXISTS opportunities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(150) NOT NULL,
 company VARCHAR(150) NOT NULL,
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('INTERNSHIP','PLACEMENT','FULL_TIME')),
 location VARCHAR(100) NOT NULL,
 compensation INT NOT NULL CHECK(compensation>=0),
 min_cgpa DECIMAL(4,2) NOT NULL CHECK(min_cgpa BETWEEN 0 AND 10),
 graduation_year INT NOT NULL CHECK(graduation_year BETWEEN 2000 AND 2100),
 deadline DATE NOT NULL,
 description VARCHAR(6000) NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','CLOSED')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS opportunity_skills (
 opportunity_id BIGINT NOT NULL REFERENCES opportunities(id),
 skill_id BIGINT NOT NULL REFERENCES skills(id),
 min_level INT NOT NULL CHECK(min_level BETWEEN 1 AND 3),
 PRIMARY KEY(opportunity_id,skill_id)
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 opportunity_id BIGINT NOT NULL REFERENCES opportunities(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('APPLIED','SHORTLISTED','INTERVIEW','OFFERED','ACCEPTED','DECLINED','REJECTED','WITHDRAWN')),
 cover_letter VARCHAR(3000) NOT NULL,
 score_at_apply DOUBLE PRECISION NOT NULL CHECK(score_at_apply BETWEEN 0 AND 100),
 profile_snapshot VARCHAR(4000) NOT NULL,
 interview_at TIMESTAMP,
 interview_location VARCHAR(300) NOT NULL DEFAULT '',
 version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,opportunity_id)
);
CREATE TABLE IF NOT EXISTS application_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES applications(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL,
 note VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS saved_opportunities (
 user_id BIGINT NOT NULL REFERENCES users(id),
 opportunity_id BIGINT NOT NULL REFERENCES opportunities(id),
 PRIMARY KEY(user_id,opportunity_id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 message VARCHAR(600) NOT NULL,
 link VARCHAR(200) NOT NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(80) NOT NULL,
 entity_id BIGINT NOT NULL,
 detail VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_app_status ON applications(status);
CREATE INDEX IF NOT EXISTS idx_app_opportunity ON applications(opportunity_id);
CREATE INDEX IF NOT EXISTS idx_opp_deadline ON opportunities(status,deadline);
CREATE INDEX IF NOT EXISTS idx_notification_user ON notifications(user_id,is_read);
CREATE INDEX IF NOT EXISTS idx_events_application ON application_events(application_id,created_at);
